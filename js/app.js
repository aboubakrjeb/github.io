function get_lang() {
    var stored;
    try { stored = localStorage.getItem('lang'); } catch (e) { }
    return (stored === 'ar' || stored === 'en') ? stored : 'nl';
}

function apply_language(lang) {
    const dict = translations[lang] || translations.nl;
    const root = document.documentElement;
    root.setAttribute('lang', lang);
    root.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

    if (dict.pageTitle) document.title = dict.pageTitle;
    const meta_description = document.querySelector('meta[name="description"]');
    if (meta_description && dict.metaDescription) meta_description.setAttribute('content', dict.metaDescription);

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) el.innerHTML = dict[key];
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
        const key = el.getAttribute('data-i18n-aria-label');
        if (dict[key] !== undefined) el.setAttribute('aria-label', dict[key]);
    });

    document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
        const key = el.getAttribute('data-i18n-alt');
        if (dict[key] !== undefined) el.setAttribute('alt', dict[key]);
    });

    document.querySelectorAll('.lang-option').forEach((option) => {
        option.setAttribute('aria-current', option.getAttribute('data-lang') === lang ? 'true' : 'false');
    });
}

function set_lang_menu_open(open) {
    const lang_switch = document.querySelector('.lang-switch');
    const lang_toggle_btn = document.querySelector('.lang-toggle');
    if (!lang_switch || !lang_toggle_btn) return;
    lang_switch.classList.toggle('open', open);
    lang_toggle_btn.setAttribute('aria-expanded', open);
}

function select_language(lang) {
    try {
        localStorage.setItem('lang', lang);
    } catch (e) {
        // Storage can be blocked (private window); the switch still works for this visit.
    }
    apply_language(lang);
    set_lang_menu_open(false);
}

function toggle_theme() {
    const root = document.documentElement;
    const newTheme = root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    root.setAttribute('data-theme', newTheme);
    try {
        localStorage.setItem('theme', newTheme);
    } catch (e) {
        // Storage can be blocked (private window); the toggle still works for this visit.
    }
}

function sync_glass_toggle() {
    const glass_toggle_btn = document.querySelector('.glass-toggle');
    if (!glass_toggle_btn) return;
    glass_toggle_btn.setAttribute('aria-pressed', document.documentElement.getAttribute('data-glass') !== 'off');
}

